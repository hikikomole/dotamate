const { test } = require('node:test');
const assert = require('node:assert/strict');
const { match } = require('../tools/test-replay-cohort');
const { buildAudit, isFresh, referencePlayers, LABELS } = require('../tools/audit-positions-stratz');
const { auditGate, buildRoleMeta } = require('../tools/build-role-meta');
const options = { patchFrom: 900 };
const ref = () => ({ p: match().players.map((p, i) => ({ h: p.heroId, r: i < 5 ? 1 : 0, pos: i % 5 + 1 })) });
test('crosscheck skips incomplete reference teams without charging our coverage', () => {
  const r = ref(); r.p[0].pos = 2; r.p[1].pos = 1;
  const a = buildAudit([match()], new Map([['1', r]]), options);
  assert.equal(a.roles[1].confusion[2], 1); assert.equal(a.roles[1].total, 2);
  assert.equal(a.roles[1].correct, 1); assert.equal(a.teams, 2);
  r.p[0].pos = 0;
  const b = buildAudit([match()], new Map([['1', r]]), options);
  assert.equal(b.ambiguous, 0); assert.equal(b.roles[1].total, 1);
  assert.equal(b.teams, 1); assert.equal(b.referenceIncompleteTeams, 1);
  assert.equal(b.referenceIncompletePlayers, 5);
  r.p[0].pos = 1;
  r.p[1].pos = 1;
  assert.equal(buildAudit([match()], new Map([['1', r]]), options).referenceIncompleteTeams, 1);
  r.p[1].pos = 2;
  r.p.push({ ...r.p[0] });
  assert.equal(buildAudit([match()], new Map([['1', r]]), options).referenceIncompleteTeams, 1);
  assert.equal(buildAudit([match()], new Map(), options).matchIds.length, 0);
  assert.equal(referencePlayers({ players: [{ heroId: 1, isRadiant: true, position: 'POSITION_5' }] })[0].pos, 5);
});
test('missing, duplicate and invalid OUR predictions are ambiguous on complete reference teams', () => {
  const m = match();
  m[LABELS] = m.players.map((p, i) => ({ s: p.slot, pos: i % 5 + 1 }));
  m[LABELS].splice(0, 1);
  m[LABELS].push({ s: m.players[1].slot, pos: 2 });
  m[LABELS].find(p => p.s === m.players[2].slot).pos = 0;
  const a = buildAudit([m], new Map([['1', ref()]]), options);
  assert.equal(a.teams, 2); assert.equal(a.referenceIncompleteTeams, 0);
  assert.equal(a.ambiguous, 3);
  assert.equal(Object.values(a.roles).reduce((n, r) => n + r.total, 0), 7);
});
test('automatic and manual gates retain thresholds; freshness tracks method version', () => {
  const matches = Array.from({ length: 50 }, (_, i) => ({ ...match(), matchId: i + 1, startTime: 1000 + i * 86400 }));
  matches[1].players = matches[1].players.map(p => ({ ...p, heroId: p.heroId + 10 }));
  const refs = new Map(matches.map(m => [String(m.matchId), { p: m.players.map((p, i) => ({ h: p.heroId, r: i < 5 ? 1 : 0, pos: i % 5 + 1 })) }]));
  const a = buildAudit(matches, refs, options);
  assert.equal(auditGate(a), true);
  assert.equal(auditGate({ ...a, method: undefined }), true);
  for (const change of [{ teams: 99 }, { matchIds: ['1'] }, { days: ['x'] }, { lineups: 1 }, { ambiguous: 56 }, { method: 'unknown' }]) assert.equal(auditGate({ ...a, ...change }), false);
  const bad = structuredClone(a); bad.roles[5].correct = 84; bad.roles[5].confusion = { 4: 16, 5: 84 };
  assert.equal(auditGate(bad), false);
  assert.equal(buildRoleMeta(matches, { version: 'x', timestamp: 900 }, null, a).meta.coverage.audit.method, 'auto-crosscheck');
  assert.equal(isFresh(a, Date.parse(a.builtAt) + 6 * 86400000), true);
  assert.equal(isFresh(a, Date.parse(a.builtAt) + 7 * 86400000), false);
  assert.equal(isFresh({ ...a, methodVersion: 0 }), false);
});
const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
test('cache-only CLI writes audit, skips fresh output and preserves it on failure', () => {
  const dir = fs.mkdtempSync(path.join(require('os').tmpdir(), 'positions-audit-'));
  const input = path.join(dir, 'data'), archive = path.join(dir, 'archive');
  fs.mkdirSync(path.join(input, 'meta-matches'), { recursive: true });
  fs.mkdirSync(path.join(archive, 'matches'), { recursive: true });
  fs.writeFileSync(path.join(input, 'patch-notes.json'), JSON.stringify({ version: 'fixture', timestamp: 900 }));
  fs.writeFileSync(path.join(input, 'heroes.json'), JSON.stringify({ heroes: match().players.map(p => ({ id: p.heroId })) }));
  fs.writeFileSync(path.join(archive, 'index.json'), JSON.stringify({ matches: [{ matchId: 1 }] }));
  fs.writeFileSync(path.join(archive, 'matches', '1.json'), JSON.stringify(match()));
  fs.writeFileSync(path.join(input, 'meta-matches', 'fixture.jsonl'), JSON.stringify({ id: 1, ...ref() }) + '\n');
  const args = ['tools/audit-positions-stratz.js', '--input-dir', input, '--archive-dir', archive, '--max', '0', '--lock-held'];
  const run = extra => spawnSync(process.execPath, [...args, ...extra], { cwd: path.join(__dirname, '..'), encoding: 'utf8', env: { ...process.env, DOTAMATE_COLLECTOR: dir } });
  assert.equal(run([]).status, 0);
  const file = path.join(archive, 'positions-audit.json'), before = fs.readFileSync(file, 'utf8');
  assert.equal(JSON.parse(before).roles[1].correct, 2);
  assert.match(run([]).stdout, /skipped/);
  assert.equal(fs.readFileSync(file, 'utf8'), before);
  fs.writeFileSync(path.join(input, 'patch-notes.json'), '{}');
  assert.equal(run(['--force']).status, 1);
  assert.equal(fs.readFileSync(file, 'utf8'), before);
});
